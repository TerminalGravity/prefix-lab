import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const baseURL=process.env.BASE_URL||'http://127.0.0.1:4189/';
const browser=await chromium.launch({executablePath:'/run/current-system/sw/bin/chromium',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader']});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(baseURL,{waitUntil:'networkidle'});
 await page.getByRole('heading',{name:'Where did the hit go?'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'01 Exact prefix'}).getAttribute('aria-current'),'page');
 assert.equal(await page.getByRole('button',{name:/System 1,600 tokens/}).getAttribute('aria-pressed'),'true');
 assert.equal(await page.locator('canvas').count(),1);
 await page.getByRole('button',{name:'New user turn'}).click();
 await page.getByText('CACHE HIT').first().waitFor();
 await page.getByText('4,000 tokens read').first().waitFor();
 await page.getByRole('button',{name:'Reset lesson'}).click();
 await page.locator('.metrics').getByText('CACHE MISS').waitFor();
 await page.mouse.click(950,495);
 await page.locator('.metrics').getByText('CACHE HIT').waitFor();
 await page.getByRole('button',{name:'Pause visualization'}).click();
 const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
 const frozen=digest(await page.locator('canvas').screenshot());
 await page.waitForTimeout(350);
 assert.equal(digest(await page.locator('canvas').screenshot()),frozen);
 await page.getByRole('button',{name:'Play visualization'}).click();
 await page.getByRole('button',{name:'02 Cache lifetime'}).click();
 await page.getByRole('heading',{name:'Keep it alive.'}).waitFor();
 assert.equal(await page.locator('.metrics').getByText('0 / 9 hits').count(),1);
 await page.getByRole('button',{name:'1 hour'}).click();
 await page.locator('.metrics').getByText('9 / 9 hits').waitFor();
 await page.getByRole('button',{name:'03 Agent economics'}).click();
 await page.getByRole('heading',{name:'The agent bill.'}).waitFor();
 await page.getByRole('button',{name:'Opus 5.5'}).click();
 await page.getByText('CHALLENGE COMPLETE').waitFor();
 await page.getByRole('button',{name:'Astra'}).click();
 assert.equal(await page.getByText('CHALLENGE COMPLETE').count(),0);
 const mobile=await browser.newPage({viewport:{width:390,height:844}});
 await mobile.goto(baseURL,{waitUntil:'networkidle'});
 assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth),390);
 await mobile.getByRole('button',{name:'02 Cache lifetime'}).click();
 await mobile.getByRole('heading',{name:'Keep it alive.'}).waitFor();
 assert.equal(await mobile.locator('.mobile-mechanism').isVisible(),true);
 await mobile.close();
 const calm=await browser.newPage({viewport:{width:1000,height:700},reducedMotion:'reduce'});
 await calm.goto(baseURL,{waitUntil:'networkidle'});
 await calm.getByRole('button',{name:'Play visualization'}).waitFor();
 const calmFrame=digest(await calm.locator('canvas').screenshot());
 await calm.waitForTimeout(250);
 assert.equal(digest(await calm.locator('canvas').screenshot()),calmFrame);
 await calm.close();
 assert.deepEqual(errors,[]);
 console.log('Prefix Lab browser: 3D, hit/miss, TTL, routing, mobile passed');
}finally{await browser.close()}
